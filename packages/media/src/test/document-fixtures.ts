import { createCanvas } from '@napi-rs/canvas';
import { existsSync } from 'node:fs';
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { crc32 } from 'node:zlib';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

/**
 * Generates the demo documents used by the document tests (and committed, small, under
 * `fixtures/documents/`). Everything is fictional and labelled demo; the play names are
 * generic football terms, no people or schools.
 *
 *   demo-playbook.pdf  3 pages with a text layer: a play page with a heading and a sketch,
 *                      a numbered play list, a "Terms" page with "Term — definition" lines.
 *   demo-scan.pdf      1 page holding only a PNG of typed text: a stand-in for a scanned
 *                      page (no text layer).
 *   demo-notes.txt     130 lines of install notes → 3 pages of 60/60/10 lines.
 *   demo-notes.docx    the first 12 lines of the notes as paragraphs (minimal WordprocessingML).
 */

export const PLAYBOOK_PDF = 'demo-playbook.pdf';
export const SCAN_PDF = 'demo-scan.pdf';
export const NOTES_TXT = 'demo-notes.txt';
export const NOTES_DOCX = 'demo-notes.docx';

export const PLAY_LIST = ['Inside Zone Right', 'Power Left', 'Counter Right', 'Jet Sweep Left', 'Boot Right', 'Four Verticals', 'Mesh', 'Smash Right'];
export const TERMS: Array<[string, string]> = [
  ['Alert', 'a built-in change to the play that the quarterback calls at the line'],
  ['Check', 'a second play called at the line that replaces the huddle call'],
  ['Kill', 'the signal that cancels the first play of a two-play call'],
  ['Trips', 'three receivers aligned to the same side of the formation'],
  ['Nub', 'the side of the formation with a tight end and no receiver'],
];

const FIXED_DATE = new Date('2026-01-01T00:00:00Z');

export function notesText(): string {
  const lines: string[] = ['DEMO install notes (fictional, generated by the media test setup)', ''];
  for (let i = 1; lines.length < 130; i++) {
    const play = PLAY_LIST[(i - 1) % PLAY_LIST.length] as string;
    lines.push(`${i}. ${play} — rep ${i}: check alignment, footwork, aiming point.`);
  }
  return `${lines.join('\n')}\n`;
}

export async function makePlaybookPdf(): Promise<Uint8Array> {
  const doc = await PDFDocument.create({ updateMetadata: false });
  setFixedMetadata(doc);
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const letter: [number, number] = [612, 792];

  // Page 1: one play with a sketch.
  const p1 = doc.addPage(letter);
  p1.drawText('DEMO PLAYBOOK — fictional', { x: 72, y: 740, size: 9, font, color: rgb(0.4, 0.4, 0.4) });
  p1.drawText('Inside Zone Right', { x: 72, y: 700, size: 24, font: bold });
  p1.drawText('Formation: Trips Right. Personnel: 11.', { x: 72, y: 670, size: 12, font });
  p1.drawText('The line steps play-side; the back aims at the outside hip of the guard and reads the first down lineman.', { x: 72, y: 650, size: 11, font });
  // Sketch: seven circles on the line, a square for the center, an arrow.
  for (let i = 0; i < 7; i++) {
    const x = 156 + i * 50;
    if (i === 3) p1.drawRectangle({ x: x - 9, y: 491, width: 18, height: 18, borderColor: rgb(0, 0, 0), borderWidth: 1.2 });
    else p1.drawCircle({ x, y: 500, size: 9, borderColor: rgb(0, 0, 0), borderWidth: 1.2 });
  }
  p1.drawCircle({ x: 306, y: 440, size: 9, borderColor: rgb(0, 0, 0), borderWidth: 1.2 });
  p1.drawLine({ start: { x: 306, y: 431 }, end: { x: 356, y: 560 }, thickness: 1.5, color: rgb(0, 0, 0) });

  // Page 2: numbered play list.
  const p2 = doc.addPage(letter);
  p2.drawText('Play List', { x: 72, y: 700, size: 24, font: bold });
  PLAY_LIST.forEach((name, i) => p2.drawText(`${i + 1}. ${name}`, { x: 72, y: 660 - i * 22, size: 12, font }));

  // Page 3: terms.
  const p3 = doc.addPage(letter);
  p3.drawText('Terms', { x: 72, y: 700, size: 24, font: bold });
  TERMS.forEach(([term, def], i) => p3.drawText(`${term} — ${def}`, { x: 72, y: 660 - i * 22, size: 11, font }));

  return doc.save({ useObjectStreams: false });
}

/** A PNG of typed text, placed on a page as the only content: no text layer. */
export function scanPagePng(): Buffer {
  const width = 1020;
  const height = 1320; // Letter at 120 dpi
  const canvas = createCanvas(width, height);
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = '#ffffff';
  ctx.fillRect(0, 0, width, height);
  ctx.fillStyle = '#111111';
  ctx.font = 'bold 48px sans-serif';
  ctx.fillText('Inside Zone Right', 120, 200);
  ctx.font = '34px sans-serif';
  ctx.fillText('1. Inside Zone Right', 120, 300);
  ctx.fillText('2. Power Left', 120, 350);
  ctx.fillText('3. Counter Right', 120, 400);
  ctx.font = '22px sans-serif';
  ctx.fillText('DEMO scanned page, fictional', 120, 1200);
  return canvas.toBuffer('image/png');
}

export async function makeScanPdf(): Promise<Uint8Array> {
  const doc = await PDFDocument.create({ updateMetadata: false });
  setFixedMetadata(doc);
  const png = await doc.embedPng(scanPagePng());
  const page = doc.addPage([612, 792]);
  page.drawImage(png, { x: 0, y: 0, width: 612, height: 792 });
  return doc.save({ useObjectStreams: false });
}

function setFixedMetadata(doc: PDFDocument): void {
  doc.setCreationDate(FIXED_DATE);
  doc.setModificationDate(FIXED_DATE);
  doc.setProducer('FootballOS media test fixtures');
  doc.setCreator('FootballOS media test fixtures');
}

/** Minimal .docx: a stored (uncompressed) zip with the three parts mammoth needs. */
export function makeDocx(paragraphs: string[]): Buffer {
  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  const body = paragraphs.map((p) => `<w:p><w:r><w:t xml:space="preserve">${esc(p)}</w:t></w:r></w:p>`).join('');
  const files: Array<[string, string]> = [
    [
      '[Content_Types].xml',
      '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/word/document.xml" ContentType="application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml"/></Types>',
    ],
    [
      '_rels/.rels',
      '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="word/document.xml"/></Relationships>',
    ],
    [
      'word/document.xml',
      `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main"><w:body>${body}</w:body></w:document>`,
    ],
  ];
  return storedZip(files.map(([name, text]) => [name, Buffer.from(text, 'utf8')]));
}

function storedZip(entries: Array<[string, Buffer]>): Buffer {
  const locals: Buffer[] = [];
  const centrals: Buffer[] = [];
  let offset = 0;
  const dosTime = 0;
  const dosDate = (2026 - 1980) << 9 | (1 << 5) | 1;
  for (const [name, data] of entries) {
    const nameBuf = Buffer.from(name, 'utf8');
    const crc = crc32(data) >>> 0;
    const local = Buffer.alloc(30);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0, 6);
    local.writeUInt16LE(0, 8); // stored
    local.writeUInt16LE(dosTime, 10);
    local.writeUInt16LE(dosDate, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(data.length, 18);
    local.writeUInt32LE(data.length, 22);
    local.writeUInt16LE(nameBuf.length, 26);
    local.writeUInt16LE(0, 28);
    const central = Buffer.alloc(46);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    central.writeUInt16LE(20, 6);
    central.writeUInt16LE(0, 8);
    central.writeUInt16LE(0, 10);
    central.writeUInt16LE(dosTime, 12);
    central.writeUInt16LE(dosDate, 14);
    central.writeUInt32LE(crc, 16);
    central.writeUInt32LE(data.length, 20);
    central.writeUInt32LE(data.length, 24);
    central.writeUInt16LE(nameBuf.length, 28);
    central.writeUInt16LE(0, 30);
    central.writeUInt16LE(0, 32);
    central.writeUInt16LE(0, 34);
    central.writeUInt16LE(0, 36);
    central.writeUInt32LE(0, 38);
    central.writeUInt32LE(offset, 42);
    locals.push(local, nameBuf, data);
    centrals.push(central, nameBuf);
    offset += local.length + nameBuf.length + data.length;
  }
  const centralSize = centrals.reduce((n, b) => n + b.length, 0);
  const eocd = Buffer.alloc(22);
  eocd.writeUInt32LE(0x06054b50, 0);
  eocd.writeUInt16LE(0, 4);
  eocd.writeUInt16LE(0, 6);
  eocd.writeUInt16LE(entries.length, 8);
  eocd.writeUInt16LE(entries.length, 10);
  eocd.writeUInt32LE(centralSize, 12);
  eocd.writeUInt32LE(offset, 16);
  eocd.writeUInt16LE(0, 20);
  return Buffer.concat([...locals, ...centrals, eocd]);
}

export interface DocumentFixturePaths {
  dir: string;
  playbookPdf: string;
  scanPdf: string;
  notesTxt: string;
  notesDocx: string;
}

/** Writes the four documents into `dir` (skipped when all exist and `force` is false). */
export async function ensureDocumentFixtures(dir: string, { force = false } = {}): Promise<DocumentFixturePaths> {
  await mkdir(dir, { recursive: true });
  const paths: DocumentFixturePaths = {
    dir,
    playbookPdf: join(dir, PLAYBOOK_PDF),
    scanPdf: join(dir, SCAN_PDF),
    notesTxt: join(dir, NOTES_TXT),
    notesDocx: join(dir, NOTES_DOCX),
  };
  if (!force && [paths.playbookPdf, paths.scanPdf, paths.notesTxt, paths.notesDocx].every((p) => existsSync(p))) return paths;
  await writeFile(paths.playbookPdf, await makePlaybookPdf());
  await writeFile(paths.scanPdf, await makeScanPdf());
  const notes = notesText();
  await writeFile(paths.notesTxt, notes);
  await writeFile(paths.notesDocx, makeDocx(notes.split('\n').slice(0, 12)));
  return paths;
}
