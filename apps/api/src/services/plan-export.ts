import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from 'pdf-lib';
import type { GamePlanVersion, Unit } from '@footballos/contracts';

/** Everything the exports print; built by the route from the plan, game, opponent and team rows. */
export type ExportContext = {
  version: GamePlanVersion;
  unit: Unit;
  team: { name: string; shortName: string; environmentKind: string };
  opponentName: string | null;
  week: number | null;
  scheduledAt: string | null;
  approvedByName: string | null;
  generatedAt: string;
};

const UNIT_LABEL: Record<Unit, string> = { offense: 'Offense', defense: 'Defense', special_teams: 'Special teams' };

function esc(s: string): string {
  return s.replace(/[&<>"']/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[ch]!);
}

function fmtDate(iso: string | null): string {
  return iso ? iso.slice(0, 16).replace('T', ' ') + ' UTC' : '—';
}

export function titleLine(x: ExportContext): string {
  return `${x.team.name} · ${UNIT_LABEL[x.unit]} game plan${x.week !== null ? ` · Week ${x.week}` : ''}${x.opponentName ? ` vs ${x.opponentName}` : ''}`;
}

export function footerLine(x: ExportContext): string {
  return `Generated by FootballOS ${x.generatedAt.slice(0, 10)} · version ${x.version.number}`;
}

/** Self-contained HTML with a print stylesheet; no scripts, no external fonts or analytics (§15.4). */
export function renderHtml(x: ExportContext): string {
  const v = x.version;
  const sections = v.sections
    .map((s) => `
      <section>
        <h2>${esc(s.title)}</h2>
        ${s.items.length === 0 ? '<p class="empty">No items.</p>' : `<ol>${[...s.items].sort((a, b) => a.order - b.order).map((i) => `<li>${esc(i.text)}${i.sourceRecommendationId ? ' <span class="tag">from recommendation</span>' : ''}</li>`).join('')}</ol>`}
      </section>`)
    .join('\n');
  const status = v.status === 'approved' ? `Approved${v.override ? ' (head coach override)' : ''} by ${esc(x.approvedByName ?? 'unknown')} on ${fmtDate(v.approvedAt)}` : `Status: ${esc(v.status)}`;
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="referrer" content="no-referrer">
<title>${esc(titleLine(x))}</title>
<style>
  :root { color-scheme: light; }
  body { font: 12pt/1.4 Georgia, "Times New Roman", serif; color: #111; margin: 24px; max-width: 820px; }
  header { border-bottom: 2px solid #111; padding-bottom: 8px; margin-bottom: 16px; }
  h1 { font-size: 18pt; margin: 0 0 4px; }
  .meta { font-size: 10pt; color: #333; }
  .env { display: inline-block; border: 1px solid #333; padding: 0 6px; font-size: 9pt; text-transform: uppercase; letter-spacing: .05em; margin-left: 8px; }
  h2 { font-size: 13pt; margin: 18px 0 6px; border-bottom: 1px solid #999; }
  ol { margin: 0; padding-left: 22px; }
  li { margin: 2px 0; }
  .empty { color: #666; font-style: italic; margin: 0; }
  .tag { font-size: 9pt; color: #555; }
  footer { margin-top: 24px; border-top: 1px solid #999; padding-top: 6px; font-size: 9pt; color: #555; }
  @media print { body { margin: 0; } section { break-inside: avoid; } a { color: inherit; text-decoration: none; } }
</style>
</head>
<body>
<header>
  <h1>${esc(titleLine(x))}<span class="env">${esc(x.team.environmentKind)}</span></h1>
  <div class="meta">${x.scheduledAt ? `Kickoff ${esc(fmtDate(x.scheduledAt))} · ` : ''}Version ${v.number} · ${status}</div>
</header>
${sections}
<footer>${esc(footerLine(x))}</footer>
</body>
</html>
`;
}

// PDF -----------------------------------------------------------------------------------------------

const PAGE = { width: 612, height: 792, margin: 54 } as const;

function wrap(text: string, font: PDFFont, size: number, maxWidth: number): string[] {
  const words = text.replace(/\s+/g, ' ').trim().split(' ');
  const lines: string[] = [];
  let line = '';
  for (const w of words) {
    const candidate = line ? `${line} ${w}` : w;
    if (font.widthOfTextAtSize(candidate, size) <= maxWidth || !line) line = candidate;
    else { lines.push(line); line = w; }
  }
  if (line) lines.push(line);
  return lines;
}

/** Server-side PDF with pdf-lib (MIT): title block, one section per template key, items, footer on every page. */
export async function renderPdf(x: ExportContext): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  doc.setTitle(titleLine(x));
  doc.setProducer('FootballOS');
  doc.setCreator('FootballOS');
  const font = await doc.embedFont(StandardFonts.Helvetica);
  const bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const width = PAGE.width - 2 * PAGE.margin;
  let page: PDFPage = doc.addPage([PAGE.width, PAGE.height]);
  let y = PAGE.height - PAGE.margin;
  const footer = (p: PDFPage) => p.drawText(footerLine(x), { x: PAGE.margin, y: PAGE.margin - 24, size: 8, font, color: rgb(0.35, 0.35, 0.35) });
  const newPage = () => { footer(page); page = doc.addPage([PAGE.width, PAGE.height]); y = PAGE.height - PAGE.margin; };
  const line = (text: string, f: PDFFont, size: number, indent = 0, color = rgb(0, 0, 0)) => {
    for (const l of wrap(text, f, size, width - indent)) {
      if (y < PAGE.margin + 8) newPage();
      page.drawText(l, { x: PAGE.margin + indent, y, size, font: f, color });
      y -= size * 1.35;
    }
  };
  const v = x.version;
  line(titleLine(x), bold, 15);
  line(`Environment: ${x.team.environmentKind}${x.scheduledAt ? ` · Kickoff ${fmtDate(x.scheduledAt)}` : ''}`, font, 9, 0, rgb(0.25, 0.25, 0.25));
  line(`Version ${v.number} · ${v.status === 'approved' ? `Approved${v.override ? ' (head coach override)' : ''} by ${x.approvedByName ?? 'unknown'} on ${fmtDate(v.approvedAt)}` : `Status: ${v.status}`}`, font, 9, 0, rgb(0.25, 0.25, 0.25));
  y -= 6;
  page.drawLine({ start: { x: PAGE.margin, y }, end: { x: PAGE.width - PAGE.margin, y }, thickness: 1 });
  y -= 14;
  for (const s of v.sections) {
    if (y < PAGE.margin + 40) newPage();
    line(s.title, bold, 11.5);
    if (s.items.length === 0) line('No items.', font, 9.5, 10, rgb(0.4, 0.4, 0.4));
    [...s.items].sort((a, b) => a.order - b.order).forEach((it, i) => line(`${i + 1}. ${it.text}`, font, 10, 10));
    y -= 6;
  }
  footer(page);
  return doc.save();
}
